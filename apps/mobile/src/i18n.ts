export function texto(idioma: Idioma, clave: ClaveTexto): string {
  return TEXTOS[idioma][clave];
}

/** Etiqueta visible de un estado de pedido (los literales van en inglés). */
export function etiquetaEstado(idioma: Idioma, estado: string): string {
  const clave = `estado_${estado}` as ClaveTexto;
  if ((CLAVES as readonly string[]).includes(clave)) {
    return TEXTOS[idioma][clave];
  }
  return estado;
}
