const CLAVE_ALMACEN = "kourigo.admin.idioma";

function leerIdiomaGuardado(): Idioma {
  try {
    const valor = window.localStorage.getItem(CLAVE_ALMACEN);
    return valor === "fr" || valor === "es" ? valor : "ht";
  } catch {
    return IDIOMA_POR_DEFECTO;
  }
}

interface ContextoIdioma {
  readonly idioma: Idioma;
  readonly fijarIdioma: (nuevo: Idioma) => void;
  readonly t: (clave: ClaveTexto) => string;
}

const Contexto = createContext<ContextoIdioma | null>(null);

export function ProveedorIdioma({ children }: { readonly children: ReactNode }) {
  const [idioma, setIdioma] = useState<Idioma>(leerIdiomaGuardado);
  useEffect(() => {
    try {
      window.localStorage.setItem(CLAVE_ALMACEN, idioma);
    } catch {
      // Sin almacenamiento disponible (navegación privada): la elección
      // simplemente no persiste entre recargas.
    }
  }, [idioma]);
  const valor = useMemo<ContextoIdioma>(
    () => ({
      idioma,
      fijarIdioma: setIdioma,
      t: (clave: ClaveTexto) => texto(idioma, clave),
    }),
    [idioma],
  );
  return <Contexto.Provider value={valor}>{children}</Contexto.Provider>;
}

export function useIdioma(): ContextoIdioma {
  const valor = useContext(Contexto);
  if (valor === null) {
    throw new Error("useIdioma debe usarse dentro de ProveedorIdioma.");
  }
  return valor;
}

/** Selector de idioma (kreyòl prioritario, luego français y español). */
export function SelectorIdioma() {
  const { idioma, fijarIdioma, t } = useIdioma();
  return (
    <select
      className="selector-idioma"
      value={idioma}
      aria-label={t("idioma")}
      onChange={(e) => fijarIdioma(e.target.value as Idioma)}
    >
      {IDIOMAS.map((codigo) => (
        <option key={codigo} value={codigo}>
          {ETIQUETA_IDIOMA[codigo]}
        </option>
      ))}
    </select>
  );
}
